#!/usr/bin/env python3
"""Scheduled pregame *read-only* preview. Never creates authentic predictions."""
import argparse, hashlib, json, os, sys
from datetime import datetime, timezone, timedelta
from pathlib import Path
from phase3d37b_roster_match import BASE, fetch
from phase3d37c_crosswalk import utc
from phase3d37d_readiness import run as readiness_run
from phase3d36c_supabase_stats import fetch_latest

UTC=timezone.utc

def current_week(payload):
    season=payload.get('season') or {}
    week=payload.get('week') or {}
    year=season.get('year')
    number=week.get('number')
    season_type=season.get('type')
    if not isinstance(year,int) or not isinstance(number,int) or not (2000<=year<=2100 and 1<=number<=18) or season_type!=2:
        raise ValueError('Unable to verify current regular-season week')
    return year,number

def freshness(generated, now, max_hours):
    timestamp=utc(generated)
    if not timestamp:return 'missing_export_timestamp'
    if timestamp>now+timedelta(minutes=5):return 'export_timestamp_in_future'
    if now-timestamp>timedelta(hours=max_hours):return 'stale_stats_export'
    return None

def prepare(readiness, source, now, max_hours):
    status=readiness.get('status')
    reason=freshness(source.get('generated_at'),now,max_hours)
    samples=readiness.get('sample_previews',[])
    # Source freshness alone is NOT a guarantee that every upstream row was published before kickoff.
    blockers=['upstream_row_publication_times_unverified','source_roster_not_historical']
    if reason:blockers.insert(0,reason)
    if status!='ok':blockers.insert(0,'readiness_audit_failed')
    if not readiness.get('recomputed_player_count'):blockers.insert(0,'no_recomputed_players')
    # Sample projections are diagnostic, not full records or betting recommendations.
    raw=source.get('csv_text','').encode('utf-8')
    fingerprint=hashlib.sha256(raw).hexdigest() if raw else None
    return {'phase':'3D37F','mode':'READ_ONLY','run_at_utc':now.isoformat(),
        'season':readiness.get('season'),'week':readiness.get('week'),
        'stats_export_generated_at':source.get('generated_at'), 'source_csv_sha256':fingerprint,
        'source_rows_declared':source.get('record_count'),
        'matched_players':readiness.get('matched_player_count',0),
        'recomputed_players':readiness.get('recomputed_player_count',0),
        'recomputed_metrics':readiness.get('recomputed_metric_count',0),
        'status_counts':readiness.get('status_counts',{}),
        'diagnostic_samples':samples[:10],
        'candidate_key_format':'season/week/game_id/espn_player_id/metric/source_csv_sha256',
        'candidate_keys_example': [f"{readiness.get('season')}/{readiness.get('week')}/{p['game_id']}/{p['espn_id']}/{metric}/{fingerprint}" for p in samples[:3] for metric in list(p.get('metrics',{}))[:2]] if fingerprint else [],
        'blocking_reasons':blockers,'readiness':'BLOCKED_FOR_AUTOMATED_SNAPSHOTS',
        'point_in_time_verified':False,'prediction_snapshots_created':0,'grades_created':0,'database_writes':0,
        'limitations':['Only the current export is available; no new raw-stat export is generated by this workflow',
          'A hash proves content identity, not historical upstream publication time',
          'Source freshness and kickoff checks do not establish calibrated prediction accuracy',
          'No odds, injuries, defense adjustment, or automatic grading are applied']}

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--season',type=int)
    parser.add_argument('--week',type=int)
    parser.add_argument('--max-export-age-hours',type=float,default=12)
    parser.add_argument('--output',default='phase3d37f-report.json')
    args=parser.parse_args()
    if not 0<args.max_export_age_hours<=168:raise ValueError('Invalid freshness window')
    now=datetime.now(UTC)
    if args.season is None or args.week is None:
        detected_season,detected_week=current_week(fetch(BASE+'/scoreboard?limit=100'))
        season=args.season if args.season is not None else detected_season
        week=args.week if args.week is not None else detected_week
    else:season,week=args.season,args.week
    if not 2000<=season<=2100 or not 1<=week<=18:raise ValueError('Invalid season/week')
    source=fetch_latest(os.environ['SUPABASE_URL'],os.environ['SUPABASE_SERVICE_ROLE_KEY'],season)
    if not source or not isinstance(source.get('csv_text'),str):raise ValueError('Missing source export')
    # Do not let the independent audit's second fetch substitute an unobserved source silently.
    readiness=readiness_run(season,week)
    if readiness.get('export_generated_at')!=source.get('generated_at'):
        raise ValueError('Source changed between acquisition and readiness audit; retry')
    report=prepare(readiness,source,now,args.max_export_age_hours)
    Path(args.output).write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
    print(json.dumps({k:report[k] for k in ('season','week','readiness','matched_players','recomputed_players','blocking_reasons','database_writes')}))
    return 0

if __name__=='__main__':
    try:sys.exit(main())
    except Exception as exc:
        print(json.dumps({'status':'failed','error_type':type(exc).__name__}),file=sys.stderr)
        sys.exit(1)
